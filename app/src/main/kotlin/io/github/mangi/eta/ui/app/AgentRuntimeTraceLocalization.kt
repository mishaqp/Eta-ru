        if (text.isBlank() || locale.language.lowercase(Locale.ROOT) != "ru") return text

        // Terminal summaries use the first line as Eta's status and the following lines as real
        // stdout/stderr preview. Never translate or otherwise mutate that output.
        val lineBreak = text.indexOf('\n')
        val headline = if (lineBreak >= 0) text.substring(0, lineBreak) else text
        val remainder = if (lineBreak >= 0) text.substring(lineBreak) else ""
        return localizeHeadline(headline) + remainder
    }

    private fun localizeHeadline(value: String): String =
        REPLACEMENTS.entries.fold(value) { current, (source, replacement) ->
            current.replace(source, replacement)
        }

